#!/usr/bin/env python3
"""Print docs/reports/COMPETITIVE-MATRIX.md from the fixture manifest and the per-tool results.

Standard library only. Every number is computed here from the JSON files. The feature rows are
written in this file and each cell carries one of three tags:

    VERIFIED    a command was run, or a file was read, in this session; the version and date are named
    SOURCED     taken from a document or a registry page, with the link and the date read
    UNVERIFIED  not run and not read, or contradicted by what was run

    python3 -I scripts/competitive_render.py --manifest fx/manifest.json \
        --results bawbel-core.json bawbel-yara.json bawbel-semgrep.json skillspector.json cisco.json \
        --bawbel-ref SHA --date 2026-11-26 > docs/reports/COMPETITIVE-MATRIX.md

No ranking is printed or intended.
"""

from __future__ import annotations

import argparse
import json
import statistics
from collections import Counter
from pathlib import Path

ABOVE_INFO = ("CRITICAL", "HIGH", "MEDIUM", "LOW")
LAYERS = ("content", "server_card", "runtime", "registry_metadata")
NAMES = {
    "bawbel-core": "bawbel, core (pattern engine)",
    "bawbel-yara": "bawbel, core and YARA",
    "bawbel-semgrep": "bawbel, core, YARA and Semgrep",
    "skillspector": "SkillSpector, static mode",
    "cisco": "Cisco skill-scanner, core analyzers",
}


def shown_command(argv: list) -> str:
    """The command as a reader runs it: the tool's name, not the path of a scratch virtualenv."""
    argv = list(argv)
    if "-m" in argv and argv[argv.index("-m") + 1] == "scanner.cli":
        return " ".join(["bawbel", *argv[argv.index("-m") + 2 :]])
    return " ".join([Path(argv[0]).name, *argv[1:]])


def flagged(entry: dict) -> bool:
    """At least one finding above INFO. The same rule for every tool."""
    return entry.get("max_severity") in ABOVE_INFO


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--manifest", required=True)
    ap.add_argument("--results", nargs="+", required=True)
    ap.add_argument("--bawbel-ref", required=True)
    ap.add_argument("--date", required=True)
    args = ap.parse_args()

    manifest = json.loads(Path(args.manifest).read_text(encoding="utf-8"))
    fixtures = {f["fixture"]: f for f in manifest["fixtures"]}
    runs = {}
    for path in args.results:
        data = json.loads(Path(path).read_text(encoding="utf-8"))
        runs[Path(path).stem] = data
    order = [k for k in NAMES if k in runs]

    ave = [f for f in manifest["fixtures"] if f["source"] == "ave-example"]
    records = sorted({f["ave_id"] for f in ave})
    by_layer = Counter(f["layer"] for f in ave)

    out: list[str] = []
    w = out.append

    w("# Capability matrix: bawbel and three other scanners, measured offline\n")
    w(
        "Report only. Nothing here changes the scanner. No tool is ranked, and the report draws no "
        "conclusion about the tools relative to each other. Every cell is tagged VERIFIED, SOURCED or UNVERIFIED. Tool "
        f"versions, commands and dates are named. Run on {args.date} (UTC), bawbel at commit "
        f"`{args.bawbel_ref}`. Generated by the scripts named at the end; no count is typed.\n"
    )
    w("## What was run\n")
    w(
        f"{len(manifest['fixtures'])} fixtures, one skill directory each: {len(ave)} are one "
        f"`example_patterns` entry of an active AVE record ({len(records)} records), and "
        f"{len(manifest['fixtures']) - len(ave)} are this repository's own test fixtures. The AVE "
        f"examples are one line of text under the same minimal frontmatter for every tool. By the "
        f"record's layer: "
        + ", ".join(f"{layer} {by_layer.get(layer, 0)}" for layer in LAYERS)
        + f". The corpus file has sha256 `{manifest['corpus_sha256']}`. Each tool was installed in "
        "its own scratch virtualenv with the network on, then run with the network disabled "
        "(`docker run --network none`), in its static or no-LLM mode, on harmless text that is only "
        "read. A tool that needs a network would have failed or fallen back, and that is a result. The bawbel "
        "run with Semgrep also set `SEMGREP_SEND_METRICS=off` and `SEMGREP_ENABLE_VERSION_CHECK=0`, because "
        "with Semgrep's default settings and no network that engine did not run in a test of it.\n"
    )
    w(
        "| Run | Command | Fixtures | Exit codes seen | Output not read | Mean seconds | Median seconds |"
    )
    w("|---|---|---:|---|---:|---:|---:|")
    for key in order:
        data = runs[key]
        res = data["results"]
        codes = Counter(str(r["exit"]) for r in res)
        command = shown_command(data["command"])
        secs = [r["seconds"] for r in res]
        w(
            f"| {NAMES[key]} | `{command}` | {len(res)} | "
            + ", ".join(f"{c} x{n}" for c, n in sorted(codes.items()))
            + f" | {sum(1 for r in res if not r['parsed'])} | {statistics.mean(secs):.2f} | "
            f"{statistics.median(secs):.2f} |"
        )
    w(
        "\nTimes are wall-clock seconds for one process per fixture, including start-up. The runs "
        "shared one machine and some ran at the same time, so the times show the order of "
        "magnitude of each tool on that machine and do not compare the tools with each other.\n"
    )
    w(
        "A fixture is **flagged** when the tool reported at least one finding above INFO. This is "
        "the same rule for every tool. Policy findings such as a missing licence field are INFO and "
        "do not count.\n"
    )

    w("## Results on the fixtures\n")
    w(
        "These are one-line examples taken from AVE records, in a minimal skill wrapper. They are "
        "not representative of real skills, they are not a benchmark, and a tool built to read "
        "whole skills with scripts and files is not shown at its best. The table says what each "
        "tool reported on these inputs and nothing else.\n"
    )
    w("### Flagged fixtures, by the record's layer\n")
    w(
        "| Run | "
        + " | ".join(layer for layer in LAYERS)
        + " | AVE examples, total | Repository fixtures |"
    )
    w("|---|" + "---:|" * (len(LAYERS) + 2))
    for key in order:
        res = {r["fixture"]: r for r in runs[key]["results"]}
        cells = []
        for layer in LAYERS:
            ids = [f["fixture"] for f in ave if f["layer"] == layer and f["fixture"] in res]
            cells.append(f"{sum(flagged(res[i]) for i in ids)} of {len(ids)}")
        ids = [f["fixture"] for f in ave if f["fixture"] in res]
        repo = [
            f["fixture"]
            for f in manifest["fixtures"]
            if f["source"] == "repo" and f["fixture"] in res
        ]
        w(
            f"| {NAMES[key]} | "
            + " | ".join(cells)
            + f" | {sum(flagged(res[i]) for i in ids)} of {len(ids)} | "
            + ", ".join(
                f"{i.replace('repo-', '')}: {'flagged' if flagged(res[i]) else 'not flagged'}"
                for i in repo
            )
            + " |"
        )

    w(
        "\nThe repository fixture `golden-skill` is `tests/fixtures/skills/malicious/malicious_skill.md`. "
        "`suppression-skill` is `tests/fixtures/skills/clean/self_referential_suppression.md`: its "
        "attack text sits inside suppression comments on purpose, so a scanner that honours those "
        "comments does not flag it and a tool that reads the comment text does. Neither result "
        "says anything about a benign skill.\n"
    )
    w("\n### Per record\n")
    w(
        "Flagged examples of each record, out of the record's examples. A cell is empty for a run that has no result.\n"
    )
    w("| Record | Layer | Examples | " + " | ".join(NAMES[k] for k in order) + " |")
    w("|---|---|---:|" + "---:|" * len(order))
    for ave_id in records:
        items = [f for f in ave if f["ave_id"] == ave_id]
        cells = []
        for key in order:
            res = {r["fixture"]: r for r in runs[key]["results"]}
            here = [res[f["fixture"]] for f in items if f["fixture"] in res]
            cells.append(f"{sum(flagged(r) for r in here)}" if here else "")
        w(f"| {ave_id} | {items[0]['layer']} | {len(items)} | " + " | ".join(cells) + " |")

    w("\n### Names each tool reported\n")
    w(
        "Rule or check identifiers as the tools print them, counted over the flagged fixtures. "
        "Names only; no rule text was kept or is reproduced.\n"
    )
    w("| Run | Distinct names | Most frequent (name: fixtures) |")
    w("|---|---:|---|")
    for key in order:
        names: Counter = Counter()
        for r in runs[key]["results"]:
            if flagged(r):
                names.update(r["rules"])
        top = ", ".join(f"`{n}`: {c}" for n, c in names.most_common(6))
        w(f"| {NAMES[key]} | {len(names)} | {top} |")

    w("\n### Agreement\n")
    w(
        "How many fixtures each combination of runs flagged, for the runs that have a result for every fixture.\n"
    )
    complete = [k for k in order if len(runs[k]["results"]) == len(manifest["fixtures"])]
    short = {
        "bawbel-core": "B",
        "bawbel-yara": "BY",
        "bawbel-semgrep": "BYS",
        "skillspector": "SS",
        "cisco": "C",
    }
    combos: Counter = Counter()
    for fid in fixtures:
        who = [
            short[k]
            for k in complete
            if flagged({r["fixture"]: r for r in runs[k]["results"]}[fid])
        ]
        combos["none" if not who else "+".join(who)] += 1
    w(
        "`"
        + "`, `".join(f"{short[k]}" for k in complete)
        + "` stand for "
        + ", ".join(NAMES[k] for k in complete)
        + ".\n"
    )
    w("| Flagged by | Fixtures |")
    w("|---|---:|")
    for combo, n in sorted(combos.items(), key=lambda kv: (-kv[1], kv[0])):
        w(f"| {combo} | {n} |")

    w(FEATURES.replace("{DATE}", args.date).replace("{REF}", args.bawbel_ref))
    print("\n".join(out))
    return 0


