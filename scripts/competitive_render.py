#!/usr/bin/env python3
"""Print docs/reports/COMPETITIVE-MATRIX.md from the fixture manifest and the per-tool results.

Standard library only. Every number is computed here from the JSON files. The feature rows are
written in this file and each cell carries one of three tags:

    VERIFIED    a command was run, or a file was read, in this session; the version and date are named
    SOURCED     taken from a document or a registry page, with the link and the date read
    UNVERIFIED  not run and not read, or contradicted by what was run

    python3 -I scripts/competitive_render.py --manifest fx/manifest.json \
        --results bawbel-core.json bawbel-yara.json bawbel-semgrep.json skillspector.json cisco.json \
        --bawbel-ref SHA --date 2026-11-26 > docs/reports/COMPETITIVE-MATRIX.md

No ranking is printed or intended.
"""

from __future__ import annotations

import argparse
import json
import statistics
from collections import Counter
from pathlib import Path

ABOVE_INFO = ("CRITICAL", "HIGH", "MEDIUM", "LOW")
LAYERS = ("content", "server_card", "runtime", "registry_metadata")
NAMES = {
    "bawbel-core": "bawbel, core (pattern engine)",
    "bawbel-yara": "bawbel, core and YARA",
    "bawbel-semgrep": "bawbel, core, YARA and Semgrep",
    "skillspector": "SkillSpector, static mode",
    "cisco": "Cisco skill-scanner, core analyzers",
}


def shown_command(argv: list) -> str:
    """The command as a reader runs it: the tool's name, not the path of a scratch virtualenv."""
    argv = list(argv)
    if "-m" in argv and argv[argv.index("-m") + 1] == "scanner.cli":
        return " ".join(["bawbel", *argv[argv.index("-m") + 2 :]])
    return " ".join([Path(argv[0]).name, *argv[1:]])


def flagged(entry: dict) -> bool:
    """At least one finding above INFO. The same rule for every tool."""
    return entry.get("max_severity") in ABOVE_INFO


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--manifest", required=True)
    ap.add_argument("--results", nargs="+", required=True)
    ap.add_argument("--bawbel-ref", required=True)
    ap.add_argument("--date", required=True)
    args = ap.parse_args()

    manifest = json.loads(Path(args.manifest).read_text(encoding="utf-8"))
    runs = {}
    for path in args.results:
        data = json.loads(Path(path).read_text(encoding="utf-8"))
        runs[Path(path).stem] = data
    order = [k for k in NAMES if k in runs]

    ave = [f for f in manifest["fixtures"] if f["source"] == "ave-example"]
    records = sorted({f["ave_id"] for f in ave})
    by_layer = Counter(f["layer"] for f in ave)

    out: list[str] = []
    w = out.append

    bawbel_keys = [k for k in order if k.startswith("bawbel")]
    other_keys = [k for k in order if not k.startswith("bawbel")]
    n_fixtures = len(manifest["fixtures"])

    w("# Capability matrix: bawbel and three other scanners, measured offline\n")
    w(
        "Report only. Nothing here changes the scanner. No tool is ranked, and the report draws no "
        "conclusion about the tools relative to each other. Every cell of the feature table is tagged "
        "VERIFIED, SOURCED or UNVERIFIED. Tool versions, commands and dates are named. Run on "
        f"{args.date} (UTC), bawbel at commit `{args.bawbel_ref}`. Generated by the scripts named at the "
        "end; no count is typed.\n"
    )
    w("## How to read the numbers\n")
    w(
        "The counts in this report are matches of each tool's rules against example text. **They were "
        "produced by our method, not by the tools' methods:** our fixtures (one-line examples written "
        "for the records of the AVE taxonomy, which this project maintains), our rule for when a fixture "
        "counts as flagged, and each tool run in its static or no-LLM mode with the options named. "
        "**They are not a comparison of the tools, and they are not a rate of detection (recall) on real "
        "attacks.** The examples were not written against any other tool, and a tool built to read "
        "whole skills with scripts and files is not fairly represented by one-line examples. Each tool's "
        "numbers are in its own section, and no table sets one tool's numbers beside another's: they "
        "are not to be added, subtracted or set against each other, here or in any post that quotes "
        "this report. The one reading this report supports is internal: the examples that our own "
        "scanner does not flag are the work to do next.\n"
    )
    w("## What was run\n")
    w(
        f"{n_fixtures} fixtures, one skill directory each: {len(ave)} are one "
        f"`example_patterns` entry of an active AVE record ({len(records)} records), and "
        f"{n_fixtures - len(ave)} are this repository's own test fixtures. The AVE "
        f"examples are one line of text under the same minimal frontmatter for every tool. By the "
        f"record's layer: "
        + ", ".join(f"{layer} {by_layer.get(layer, 0)}" for layer in LAYERS)
        + f". The corpus file has sha256 `{manifest['corpus_sha256']}`. Each tool was installed in "
        "its own scratch virtualenv with the network on, then run with the network disabled "
        "(`docker run --network none`), in its static or no-LLM mode, on harmless text that is only "
        "read. A tool that needs a network would have failed or fallen back, and that is a result. The bawbel "
        "run with Semgrep also set `SEMGREP_SEND_METRICS=off` and `SEMGREP_ENABLE_VERSION_CHECK=0`, because "
        "with Semgrep's default settings and no network that engine did not run in a test of it.\n"
    )
    w(
        "Each tool's command, exit codes and results are in its own section below.\n\n"
        "A fixture is **flagged** when the tool reported at least one finding above INFO. This is "
        "our rule, applied the same way to every tool. Policy findings such as a missing licence field "
        "are INFO and do not count.\n"
    )

    def run_lines(keys: list) -> None:
        for key in keys:
            data = runs[key]
            res = data["results"]
            codes = Counter(str(r["exit"]) for r in res)
            w(
                f"- {NAMES[key]}: `{shown_command(data['command'])}`, {len(res)} fixtures, exit codes seen "
                + ", ".join(f"{c} x{n}" for c, n in sorted(codes.items()))
                + f", output not read {sum(1 for r in res if not r['parsed'])}."
            )
        w("")

    def layer_rows(keys: list) -> None:
        w(
            "| Run | "
            + " | ".join(layer for layer in LAYERS)
            + " | AVE examples, total | Repository fixtures |"
        )
        w("|---|" + "---:|" * (len(LAYERS) + 2))
        for key in keys:
            res = {r["fixture"]: r for r in runs[key]["results"]}
            cells = []
            for layer in LAYERS:
                ids = [f["fixture"] for f in ave if f["layer"] == layer and f["fixture"] in res]
                cells.append(f"{sum(flagged(res[i]) for i in ids)} of {len(ids)}")
            ids = [f["fixture"] for f in ave if f["fixture"] in res]
            repo = [
                f["fixture"]
                for f in manifest["fixtures"]
                if f["source"] == "repo" and f["fixture"] in res
            ]
            w(
                f"| {NAMES[key]} | "
                + " | ".join(cells)
                + f" | {sum(flagged(res[i]) for i in ids)} of {len(ids)} | "
                + ", ".join(
                    f"{i.replace('repo-', '')}: {'flagged' if flagged(res[i]) else 'not flagged'}"
                    for i in repo
                )
                + " |"
            )

    def names_line(keys: list) -> None:
        w(
            "\nRule or check identifiers as the tool prints them, counted over the flagged fixtures. "
            "Names only; no rule text was kept or is reproduced.\n"
        )
        w("| Run | Distinct names | Most frequent (name: fixtures) |")
        w("|---|---:|---|")
        for key in keys:
            names: Counter = Counter()
            for r in runs[key]["results"]:
                if flagged(r):
                    names.update(r["rules"])
            top = ", ".join(f"`{n}`: {c}" for n, c in names.most_common(6))
            w(f"| {NAMES[key]} | {len(names)} | {top} |")

    def timing_line(keys: list) -> None:
        for key in keys:
            secs = [r["seconds"] for r in runs[key]["results"]]
            w(
                f"\nTime for one process per fixture, including start-up, on this machine: mean "
                f"{statistics.mean(secs):.2f} s, median {statistics.median(secs):.2f} s. The runs shared "
                "one machine and some ran at the same time, so this is an order of magnitude for this "
                "tool on this machine and nothing more."
            )

    w("## bawbel, our own scanner\n")
    w(
        "Our scanner, run by us on our examples. The three runs are the same scanner with more "
        "engines installed. The repository fixture `golden-skill` is "
        "`tests/fixtures/skills/malicious/malicious_skill.md`. `suppression-skill` is "
        "`tests/fixtures/skills/clean/self_referential_suppression.md`: its attack text sits inside "
        "suppression comments on purpose, so a scanner that honours those comments does not flag it. "
        "Neither result says anything about a benign skill.\n"
    )
    run_lines(bawbel_keys)
    layer_rows(bawbel_keys)
    if bawbel_keys:
        missed = []
        for key in bawbel_keys:
            res = {r["fixture"]: r for r in runs[key]["results"]}
            ids = [f["fixture"] for f in ave if f["fixture"] in res]
            missed.append(f"{NAMES[key]}: {sum(not flagged(res[i]) for i in ids)} of {len(ids)}")
        w(
            "\nInternal reading, for our own work. Examples that our own scanner did not flag: "
            + "; ".join(missed)
            + ". Those examples are the list to work on. This counts our own rules against example "
            "text. It is not a rate of detection on real attacks."
        )
    w("\n### Per record, our scanner\n")
    w(
        "Flagged examples of each record, out of the record's examples, by our own scanner. A cell is "
        "empty for a run that has no result. Records with no flagged example are the work list.\n"
    )
    w("| Record | Layer | Examples | " + " | ".join(NAMES[k] for k in bawbel_keys) + " |")
    w("|---|---|---:|" + "---:|" * len(bawbel_keys))
    for ave_id in records:
        items = [f for f in ave if f["ave_id"] == ave_id]
        cells = []
        for key in bawbel_keys:
            res = {r["fixture"]: r for r in runs[key]["results"]}
            here = [res[f["fixture"]] for f in items if f["fixture"] in res]
            cells.append(f"{sum(flagged(r) for r in here)}" if here else "")
        w(f"| {ave_id} | {items[0]['layer']} | {len(items)} | " + " | ".join(cells) + " |")
    names_line(bawbel_keys)
    timing_line(bawbel_keys)

    for key in other_keys:
        tool = NAMES[key].split(",")[0]
        w(f"\n## {NAMES[key]}\n")
        w(
            f"Run by us, with our method: our {len(ave)} examples and our rule for a flagged fixture, the "
            f"tool's static or no-LLM mode, offline, with the command shown above. This is not "
            f"{tool}'s own method, benchmark or documented measure, and the examples were not written "
            "against it. The numbers say what it reported on these inputs and nothing else.\n"
        )
        run_lines([key])
        layer_rows([key])
        names_line([key])
        timing_line([key])
        w("")

    w(FEATURES.replace("{DATE}", args.date).replace("{REF}", args.bawbel_ref))
    print("\n".join(out))
    return 0


